import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';

describe('Karrot-style chat push / realtime alerts', () => {
  it('wires Web Push SW, inbox realtime, Messages badge, and match-code chat intact', async () => {
    const api = await readFile(resolve('src/lib/push-api.ts'), 'utf8');
    const inbox = await readFile(resolve('src/lib/chat-inbox-alerts.ts'), 'utf8');
    const sw = await readFile(resolve('public/sw.js'), 'utf8');
    const chat = await readFile(resolve('src/lib/chat-api.ts'), 'utf8');
    const hub = await readFile(resolve('src/components/ChatHub.tsx'), 'utf8');
    const schedule = await readFile(resolve('src/components/ScheduleHub.tsx'), 'utf8');
    const banner = await readFile(resolve('src/components/PushEnableBanner.tsx'), 'utf8');
    const drawer = await readFile(resolve('src/components/MatchChatDrawer.tsx'), 'utf8');
    const board = await readFile(resolve('src/components/InstantPickupBoard.tsx'), 'utf8');
    const router = await readFile(resolve('server/push-router.ts'), 'utf8');
    const edge = await readFile(resolve('supabase/functions/send-chat-push/index.ts'), 'utf8');
    const sql = await readFile(resolve('db/migrations/0078_chat_push_subscriptions.sql'), 'utf8');
    const sqlFix = await readFile(resolve('db/migrations/0083_fix_upsert_push_subscription.sql'), 'utf8');

    expect(api).toContain("rpc('upsert_push_subscription'");
    expect(api).toContain('VITE_VAPID_PUBLIC_KEY');
    expect(api).toContain('Notification.requestPermission');
    expect(api).toContain('pushManager.subscribe');
    expect(api).toContain('send-chat-push');
    expect(api).toContain("kind: 'chat'");
    expect(api).toContain("kind: 'match'");
    expect(api).toContain('headers.apikey');
    expect(api).toContain('/api/push/notify-chat');
    expect(api).toContain('Add to Home Screen');
    expect(api).toContain('notifyChatPeerFromClient');
    expect(api).toContain('notifyMatchPeerFromClient');
    expect(api).toContain('syncSubscription');
    expect(chat).toContain('notifyChatPeerFromClient');
    expect(chat).toContain("send_chat_message");
    expect(inbox).toContain("table: 'chat_messages'");
    expect(inbox).toContain("table: 'instant_pickup_requests'");
    expect(inbox).toContain('applyUnreadDocumentTitle');
    expect(inbox).toContain('roomContextLabel');
    expect(inbox).toContain('getActiveRoomId');
    expect(inbox).toContain('shouldSuppressInboxBanner');
    expect(inbox).toContain('document.hidden');
    expect(inbox).toContain('sender_id === userId');
    expect(inbox).not.toContain('send-chat-push');
    const sqlRealtime = await readFile(resolve('db/migrations/0084_fix_chat_realtime_alerts_rls.sql'), 'utf8');
    expect(sqlRealtime).toMatch(/chat_messages_select/);
    expect(sqlRealtime).toMatch(/replica identity full/i);
    expect(sqlRealtime).toMatch(/upsert_push_subscription/);
    expect(sw).toContain("addEventListener('push'");
    expect(sw).toContain("addEventListener('notificationclick'");
    expect(sw).toContain('openChat');
    expect(sw).toContain('chatDeepLink');
    expect(sw).toContain("type: 'open-chat'");
    expect(sw).toContain('roomId');
    expect(sw).toContain('silent: false');
    expect(sw).toContain('renotify: true');
    expect(sw).toContain('vibrate: [200, 100, 200]');
    expect(sw).toContain('listingId');
    expect(sw).toContain('matchId');
    expect(edge).toContain('roomId');
    expect(edge).toContain('senderName');
    expect(edge).toContain('listingId');
    expect(edge).toContain('matchId');
    expect(schedule).toContain('cueInboxAlert');
    expect(schedule).toContain('armInboxAlertAudio');
    expect(api).toContain('persistBrowserSubscription');
    expect(api).toContain('lastPersistedEndpoint');
    expect(api).toContain('applicationServerKeysMatch');
    expect(api).toContain('shouldRotateSubscription');
    expect(api).toContain('forceRotate: true');
    expect(api).toContain("lastPersistedEndpoint === existing.endpoint ? 'subscribed' : 'granted'");
    expect(hub).toContain('PushNotifyToggle');
    expect(hub).toContain('One-time match code');
    expect(hub).toContain('chatApi.send');
    expect(hub).toContain('roomContextLabel');
    expect(schedule).toContain('PushEnableBanner');
    expect(schedule).toContain('inbox-toast-layer');
    expect(schedule).toContain('forceMessages');
    expect(schedule).toContain('onActiveMatchRoomChange');
    expect(banner).toContain('Enable message alerts');
    expect(banner).toContain('pushApi.enable');
    expect(banner).toContain('syncSubscription');
    expect(drawer).toContain('encodeHouseholdCodeCard');
    expect(drawer).toContain('chatApi.send');
    expect(board).toContain('notifyMatchPeerFromClient');
    expect(board).toContain('onActiveMatchRoomChange');
    expect(router).toContain('list_push_targets_for_chat_peer');
    expect(router).toContain('webpush.sendNotification');
    expect(router).toContain('openChat');
    expect(edge).toContain('Deno.env.get');
    expect(edge).toContain('VAPID_PRIVATE_KEY');
    expect(edge).toContain('VITE_VAPID_PUBLIC_KEY');
    expect(edge).toContain('VAPID_PUBLIC_KEY');
    expect(edge).toContain('@block65/webcrypto-web-push');
    expect(edge).toContain('buildPushPayload');
    expect(edge).toContain('push_subscriptions');
    expect(edge).toContain('chatDeepLink');
    expect(edge).toContain('callerDisplayName');
    expect(edge).toMatch(/404|410/);
    expect(edge).toContain('normalizeVapidSubject');
    expect(edge).toContain('cleanVapidKey');
    expect(edge).toContain('isStalePushStatus');
    expect(edge).toContain('forbidden_vapid_or_unauthorized');
    expect(router).toContain('normalizeVapidSubject');
    expect(router).toContain('isStalePushStatus');
    expect(sql).toMatch(/chat_messages/);
    expect(sql).toMatch(/instant_pickup_requests/);
    expect(sql).toMatch(/push_subscriptions/i);
    expect(sql).toMatch(/user_id/i);
    expect(sql).toMatch(/endpoint/i);
    expect(sql).toMatch(/p256dh/i);
    expect(sql).toMatch(/\bauth\b/i);
    expect(sql).toMatch(/user_agent/i);
    expect(sql).toMatch(/updated_at/i);
    expect(sql).toMatch(/coalesce\(excluded\.user_agent, sub\.user_agent\)/);
    expect(sqlFix).toMatch(/upsert_push_subscription/);
    expect(sqlFix).toMatch(/coalesce\(excluded\.user_agent, sub\.user_agent\)/);
    expect(sqlFix).toMatch(/notify pgrst, 'reload schema'/);
    expect(sql).not.toMatch(
      /\b(amount|price|currency|money|fee|payment|phone|mobile|nickname|photo_url|latitude|longitude)\s+(text|numeric|integer|bigint|smallint|double precision|jsonb)\b/i,
    );
  });
});
