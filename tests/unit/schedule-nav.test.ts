import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';

describe('Schedule dashboard navigation', () => {
  it('locks five tabs, AppHeader location chip, ChatHub and InstantPickupBoard', async () => {
    const nav = await readFile(resolve('src/components/ScheduleNav.tsx'), 'utf8');
    const hub = await readFile(resolve('src/components/ScheduleHub.tsx'), 'utf8');
    const app = await readFile(resolve('src/App.tsx'), 'utf8');
    const css = await readFile(resolve('src/styles.css'), 'utf8');
    const chip = await readFile(resolve('src/components/LocationChip.tsx'), 'utf8');
    const quick = await readFile(resolve('src/components/QuickActions.tsx'), 'utf8');

    expect(nav).toContain('data-schedule-tab="today"');
    expect(nav).toContain('data-schedule-tab="calendar"');
    expect(nav).toContain('data-schedule-tab="matches"');
    expect(nav).toContain('data-schedule-tab="messages"');
    expect(nav).toContain('data-schedule-tab="community"');
    expect(nav).toMatch(/>\s*Messages\s*<\/button>/);
    expect(nav.indexOf('schedule-tab-matches')).toBeLessThan(nav.indexOf('schedule-tab-messages'));
    expect(nav.indexOf('schedule-tab-messages')).toBeLessThan(nav.indexOf('schedule-tab-community'));

    expect(css).toContain('grid-template-columns: repeat(5, minmax(0, 1fr)) !important');
    expect(css).toContain('.schedule-tab[data-schedule-tab="messages"]');
    expect(css).toContain('#F8FAFC');
    expect(css).toContain('#FF6B6B');
    expect(css).toContain('#1E3A8A');
    expect(css).toContain('#7C3AED');
    expect(css).toContain('wordmark--joyful');
    expect(css).toContain('wordmark__icon');
    expect(css).toContain('wordmark__text');
    expect(css).toContain('gap: 12px');
    expect(css).toContain('.quick-actions');
    expect(css).toContain('.my-trust-chip');
    expect(css).toContain('.marketplace-ask');
    expect(css).toContain('topbar__actions');

    expect(app).toContain('showSchoolLocation={showLocation}');
    expect(app).toContain('verificationPending={verificationPending}');
    expect(app).toContain('Pending Verification');
    expect(app).toContain('<LocationChip');
    expect(app).toContain('<MyTrustChip');
    expect(app).toContain('FALLBACK_SCHOOL_LOCATION');
    expect(app).toContain('SchoolRunWordmark');
    expect(app).toContain('Safe Rides, Share & Save');
    expect(app).toContain('wordmark__schoolrun');
    expect(app).toContain('wordmark__village');
    expect(app).toContain('topbar__actions');
    expect(chip).toContain('Harbourview');
    expect(chip).toContain('Sample Harbourview Primary School');
    expect(chip).toContain('schoolSectorBadge');
    expect(chip).toContain('VIC, AU');
    expect(chip).toContain('formatLocationPill');
    expect(chip).toContain('location-selector-modal');
    expect(app).toContain('topbar__sign-out');
    expect(css).toContain('min-height: 64px');
    expect(css).toContain('gap: .75rem');

    expect(quick).toContain('Instant Pickup');
    expect(quick).toContain('Marketplace');
    expect(quick).toContain('Parent Trust');
    expect(quick).toContain('Relay Share');
    expect(quick).toContain('Hot Deals');
    expect(hub).toContain('<QuickActions');
    expect(hub).toContain('<ScheduleNav');
    expect(hub.indexOf('<QuickActions')).toBeLessThan(hub.indexOf('<ScheduleNav'));
    expect(hub.indexOf('<ScheduleNav')).toBeLessThan(hub.indexOf('schedule-hero'));
    expect(hub).toContain("view === 'messages'");
    expect(hub).toContain('<ChatHub');
    expect(hub).toContain("view === 'today'");
    expect(hub).toContain('<InstantPickupBoard');
    expect(hub).toContain('userId={userId}');
    expect(hub).toContain('defaultSuburb={registeredSuburb}');
    expect(hub).toContain('onOpenChat={openChatRoom}');
    expect(hub).toContain('📋 Copy');
    expect(hub).toContain("focus === 'deals'");
    expect(hub).toContain('hot-deals-title');
    expect(hub).toContain('initialPanel={communityPanel}');
    expect(hub).toContain('segmented-toggle');
    expect(hub).toContain('I can help');
    expect(hub).toContain('Drop-off (Morning)');
    expect(hub).toContain('Pickup (Afternoon)');
    expect(hub).toContain('day-chip');
    expect(hub).toContain('time-preset');
    expect(hub).toContain('suburb-autofill');
    expect(hub).toContain('Share Private Confirmation Code');
    expect(hub).toContain('status-tag--active');
    expect(css).toContain('.segmented-toggle');
    expect(css).toContain('.day-chip--active');
    expect(css).toContain('.status-tag--active');
    expect(css).toContain('household-code__trigger');

    const community = await readFile(resolve('src/components/CommunityHub.tsx'), 'utf8');
    expect(community).toContain('<HotDealsBoard');
    expect(community).toContain('<PartnerHub');
    expect(community).toContain('Become a Partner');
    expect(community).toContain('Instant Pickup');
    expect(community).toContain('Parent Trust');
    expect(community).toContain('Relay Share');
    expect(community).toContain('<ParentTrustPanel');
    expect(community).toContain('community-partner-footer');
    expect(css).toContain('.commercial-cta');
    expect(css).toContain('.hot-deal-card');

    const board = await readFile(resolve('src/components/InstantPickupBoard.tsx'), 'utf8');
    expect(board).toContain('Request Match');
    expect(board).toContain('MatchChatDrawer');
    expect(board).toContain('onOpenChat');
    expect(board).toContain('nonPaymentNoticeForTrade');
    expect(board).toContain('PICKUP_NO_SHOW_POLICY_COPY');
    expect(board).toContain("pickup_dropoff");
    expect(board).toContain('Free Handover');
    expect(board).toContain('Trust Score Applied');
    expect(board).toContain('segmented-toggle');
    expect(board).toContain('note-chip');
    expect(board).toContain('suburb-autofill');
    expect(board).toContain('instant-compose__cta');
    expect(css).toContain('.instant-policy-badge');
    expect(css).toContain('.note-chip');
  });
});
